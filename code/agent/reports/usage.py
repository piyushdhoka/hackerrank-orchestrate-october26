"""Token usage: the per-call ledger (JSONL) -> per-model and overall totals -> usage_report.md.

Live calls are what this run spent. Cache hits replay a response bought by an earlier run, so their
original token counts are shown separately and cost nothing now. Prices come only from
code/config/pricing.json; an unpriced model is reported as 'not configured', never estimated.
"""
from __future__ import annotations

import json
from pathlib import Path


def write_ledger(path: Path, calls: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        for c in calls:
            fh.write(json.dumps(c, ensure_ascii=False, sort_keys=True) + "\n")


def load_ledger(path: Path) -> list[dict]:
    if not Path(path).exists():
        return []
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]


def load_prices(path: Path) -> dict:
    if not Path(path).exists():
        return {}
    models = json.loads(Path(path).read_text(encoding="utf-8")).get("models", {})
    return {m: p for m, p in models.items()
            if p.get("input_per_mtok") is not None and p.get("output_per_mtok") is not None}


def summarize(calls: list[dict], prices: dict, n_requests: int) -> dict:
    models: dict[str, dict] = {}
    for c in calls:
        key = f"{c['provider']}:{c['model']}"
        m = models.setdefault(key, {"provider": c["provider"], "model": c["model"], "live_calls": 0, "cached_calls": 0,
                                    "input_tokens": 0, "output_tokens": 0, "cached_input_tokens": 0,
                                    "cached_output_tokens": 0, "failed_calls": 0, "purposes": {}})
        if c.get("error"):
            m["failed_calls"] += 1          # provider error: nothing returned, nothing billed by us
            continue
        tin, tout = int(c.get("input_tokens") or 0), int(c.get("output_tokens") or 0)
        purpose = str(c.get("purpose", "")).split(":")[0]
        m["purposes"][purpose] = m["purposes"].get(purpose, 0) + 1
        if c.get("cached"):
            m["cached_calls"] += 1
            m["cached_input_tokens"] += tin
            m["cached_output_tokens"] += tout
        else:
            m["live_calls"] += 1
            m["input_tokens"] += tin
            m["output_tokens"] += tout
    unpriced = []
    for m in models.values():
        m["total_tokens"] = m["input_tokens"] + m["output_tokens"]
        p = prices.get(m["model"])
        if p:
            m["cost_usd"] = m["input_tokens"] * p["input_per_mtok"] / 1e6 + m["output_tokens"] * p["output_per_mtok"] / 1e6
        else:
            m["cost_usd"] = None if m["live_calls"] else 0.0
            if m["live_calls"]:
                unpriced.append(m["model"])
    overall = {k: sum(m[k] for m in models.values()) for k in
               ("live_calls", "cached_calls", "failed_calls", "input_tokens", "output_tokens", "total_tokens",
                "cached_input_tokens", "cached_output_tokens")}
    overall["cost_usd"] = None if unpriced else sum(m["cost_usd"] for m in models.values())
    overall["requests"] = n_requests
    overall["tokens_per_request"] = overall["total_tokens"] / n_requests if n_requests else 0.0
    overall["calls_per_request"] = overall["live_calls"] / n_requests if n_requests else 0.0
    overall["cost_per_request"] = (overall["cost_usd"] / n_requests) if (overall["cost_usd"] is not None and n_requests) else None
    overall["unpriced_models"] = unpriced
    return {"models": models, "overall": overall}


def _money(v) -> str:
    return "not configured" if v is None else f"${v:,.4f}"


def render(summary: dict, meta: dict) -> str:
    o, models = summary["overall"], summary["models"]
    lines = ["# Usage report", "",
             "Generated by `python code/main.py` from the logged token ledger of the run that produced "
             "`output.csv` (`runs/eval/llm_calls.jsonl`). Do not edit by hand.", ""]
    lines += [f"- **{k}:** {v}" for k, v in meta.items()]
    lines += ["", "## Per-model totals", "",
              "| Provider | Model | Model calls (live) | Cache hits | Failed calls | Input tokens | Output tokens | Total tokens | Estimated cost (USD) | Used for |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    for key in sorted(models):
        m = models[key]
        used = ", ".join(f"{p} ({n})" for p, n in sorted(m["purposes"].items()))
        lines.append(f"| {m['provider']} | {m['model']} | {m['live_calls']} | {m['cached_calls']} | {m['failed_calls']} | {m['input_tokens']:,} | "
                     f"{m['output_tokens']:,} | {m['total_tokens']:,} | {_money(m['cost_usd'])} | {used} |")
    if not models:
        lines.append("| - | - | 0 | 0 | 0 | 0 | 0 | 0 | $0.0000 | - |")
    lines += ["", "## Overall", "",
              "| Metric | Value |", "|---|---:|",
              f"| Requests processed | {o['requests']} |",
              f"| Model calls (live) | {o['live_calls']} |",
              f"| Cache hits | {o['cached_calls']} |",
              f"| Failed calls (provider errors, fell back) | {o['failed_calls']} |",
              f"| Input tokens | {o['input_tokens']:,} |",
              f"| Output tokens | {o['output_tokens']:,} |",
              f"| Total tokens | {o['total_tokens']:,} |",
              f"| Average tokens per request | {o['tokens_per_request']:,.1f} |",
              f"| Average model calls per request | {o['calls_per_request']:.3f} |",
              f"| Estimated cost (USD) | {_money(o['cost_usd'])} |",
              f"| Estimated cost per request (USD) | {_money(o['cost_per_request'])} |",
              f"| Tokens replayed from cache (not billed this run) | {o['cached_input_tokens'] + o['cached_output_tokens']:,} |",
              ""]
    if not o["live_calls"] and not o["cached_calls"] and not o["failed_calls"]:
        lines += ["No model calls were made in this run: both LLM gates were unavailable or disabled, so every "
                  "decision came from the deterministic first pass.", ""]
    if o["unpriced_models"]:
        lines += [f"Pricing is not configured for: {', '.join(sorted(o['unpriced_models']))}. Add per-million-token "
                  "prices to `code/config/pricing.json` to estimate cost; no prices are assumed.", ""]
    return "\n".join(lines)
